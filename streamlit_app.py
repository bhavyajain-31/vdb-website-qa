"""
VDB Website QA: web front end (Streamlit).

The tests themselves run on GitHub Actions (real browsers need a proper machine); this page lets anyone
start a run, watch it, and read the report without GitHub knowledge.

Two modes:
  github (default) - starts the "Website QA" workflow in your GitHub repository and shows its reports.
                     Works on Streamlit Community Cloud. Needs the secrets listed in README → Web front end.
  local            - runs the tool on the same machine as this page (a server or laptop with Node.js 20+).
                     Set QA_MODE = "local" in secrets or as an environment variable.
"""
from __future__ import annotations

import base64
import io
import json
import os
import re
import subprocess
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path

import requests
import streamlit as st
import streamlit.components.v1 as components

st.set_page_config(page_title="VDB Website QA", page_icon="💎", layout="wide")

ROOT = Path(__file__).resolve().parent


def secret(name: str, default: str | None = None) -> str | None:
    try:
        if name in st.secrets:
            return str(st.secrets[name])
    except Exception:  # no secrets file
        pass
    return os.environ.get(name, default)


MODE = (secret("QA_MODE", "github") or "github").lower()
REPO = secret("GITHUB_REPO")  # "owner/repo"
TOKEN = secret("GITHUB_TOKEN")
WORKFLOW = secret("WORKFLOW_FILE", "qa.yml")
BRANCH = secret("GITHUB_BRANCH", "main")
PASSWORD = secret("APP_PASSWORD")
API = "https://api.github.com"

RUN_CHOICES = {
    "Test everything (new testing cycle)": "new-cycle",
    "Continue the previous cycle (only what is not tested yet)": "continue",
    "Re-test only the failures (after a fix)": "retest-failed",
}

# ------------------------------------------------------------------ access
if PASSWORD:
    if not st.session_state.get("ok"):
        st.title("VDB Website QA")
        pw = st.text_input("Password", type="password")
        if pw and pw == PASSWORD:
            st.session_state["ok"] = True
            st.rerun()
        elif pw:
            st.error("Wrong password")
        st.stop()


# ------------------------------------------------------------------ report helpers
def inline_screenshots(html: str, files: dict[str, bytes]) -> str:
    """The dashboard references screenshots/xxx.jpg next to it; inside Streamlit there is no folder, so embed them."""
    def repl(m: re.Match) -> str:
        data = files.get(m.group(0))
        return f"data:image/jpeg;base64,{base64.b64encode(data).decode()}" if data else m.group(0)
    return re.sub(r"screenshots/[A-Za-z0-9_.-]+\.jpg", repl, html)


def show_report(files: dict[str, bytes], label: str, zip_bytes: bytes | None = None) -> None:
    if "results.json" not in files or "dashboard.html" not in files:
        st.warning("This run did not produce a report (the tool may have stopped early). Open the run on GitHub to see its log.")
        return
    res = json.loads(files["results.json"])
    s = res.get("summary", {})
    st.subheader(f"Report: {label}")
    c = st.columns(6)
    c[0].metric("Links checked", s.get("total", 0))
    c[1].metric("Passed", s.get("pass", 0) + s.get("warn", 0))
    c[2].metric("Failed", s.get("fail", 0))
    c[3].metric("Couldn't verify", s.get("blocked", 0))
    c[4].metric("Not run yet", s.get("pending", 0))
    c[5].metric("Broken images", s.get("images", {}).get("failed", 0))
    c = st.columns(3)
    c[0].metric("Critical problems", s.get("critical", 0))
    c[1].metric("Slow pages", s.get("performance", 0))
    c[2].metric("Minor issues", s.get("minor", 0))
    if s.get("pending"):
        st.info(f"{s['pending']} links were not reached before the time limit. Start a run with "
                "“Continue the previous cycle” to finish them; finished results are kept.")
    d = st.columns(4)
    d[0].download_button("Download dashboard (HTML)", inline_screenshots(files["dashboard.html"].decode(), files).encode(), "dashboard.html", "text/html")
    if "deeplinks.csv" in files:
        d[1].download_button("Download all links (CSV)", files["deeplinks.csv"], "deeplinks.csv", "text/csv")
    if "homepage-links.csv" in files:
        d[2].download_button("Download homepage links (CSV)", files["homepage-links.csv"], "homepage-links.csv", "text/csv")
    if zip_bytes:
        d[3].download_button("Download full report (ZIP)", zip_bytes, "qa-report.zip", "application/zip")
    html = inline_screenshots(files["dashboard.html"].decode(), files)
    # the dashboard is generated by this tool from the store's pages (trusted content)
    if hasattr(st, "iframe"):
        st.iframe(html, height=1500)
    else:  # older Streamlit
        components.html(html, height=1500, scrolling=True)


def files_from_zip(data: bytes) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for n in z.namelist():
            if not n.endswith("/"):
                out[n.split("reports/latest/")[-1].lstrip("./")] = z.read(n)
    return out


def ago(iso: str | None) -> str:
    if not iso:
        return ""
    t = datetime.fromisoformat(iso.replace("Z", "+00:00"))
    m = int((datetime.now(timezone.utc) - t).total_seconds() // 60)
    return f"{m} min ago" if m < 120 else t.astimezone().strftime("%d %b %Y, %H:%M")


# ------------------------------------------------------------------ GitHub mode
def gh(method: str, path: str, **kw):
    h = {"Authorization": f"Bearer {TOKEN}", "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    r = requests.request(method, f"{API}{path}", headers=h, timeout=60, **kw)
    if r.status_code >= 400:
        raise RuntimeError(f"GitHub said {r.status_code}: {r.text[:300]}")
    return r


@st.cache_data(ttl=3600, show_spinner="Downloading report…")
def artifact_zip(artifact_id: int) -> bytes:
    return gh("GET", f"/repos/{REPO}/actions/artifacts/{artifact_id}/zip").content


def github_mode() -> None:
    if not (REPO and TOKEN):
        st.error("Setup needed: add GITHUB_REPO (owner/repo) and GITHUB_TOKEN to this app's secrets. See README → Web front end.")
        st.stop()

    with st.sidebar:
        st.header("Start a test")
        choice = st.radio("What should be tested?", list(RUN_CHOICES), index=0)
        st.caption("A full test takes about 20–25 minutes. You can close this page; the test keeps running on GitHub.")
        if st.button("▶ Start test", type="primary", use_container_width=True):
            try:
                gh("POST", f"/repos/{REPO}/actions/workflows/{WORKFLOW}/dispatches", json={"ref": BRANCH, "inputs": {"mode": RUN_CHOICES[choice]}})
                st.success("Started. It appears in the list in a few seconds.")
                time.sleep(4)
                st.rerun()
            except RuntimeError as e:
                st.error(str(e))
        st.divider()
        st.caption(f"Repository: {REPO} · workflow {WORKFLOW}")

    @st.fragment(run_every=20)
    def runs_panel() -> None:
        runs = gh("GET", f"/repos/{REPO}/actions/workflows/{WORKFLOW}/runs", params={"per_page": 10}).json().get("workflow_runs", [])
        st.subheader("Test runs")
        if not runs:
            st.info("No runs yet. Start one from the left.")
            return
        for r in runs:
            status = r["status"]
            icon = {"completed": "✅" if r.get("conclusion") == "success" else "⚠️", "in_progress": "⏳", "queued": "🕒"}.get(status, "•")
            started = r.get("run_started_at") or r.get("created_at")
            cols = st.columns([5, 2, 2, 2])
            cols[0].markdown(f"{icon} **{r.get('display_title') or r['name']}**  \n<small>{ago(started)} · run #{r['run_number']}</small>", unsafe_allow_html=True)
            if status != "completed":
                mins = (datetime.now(timezone.utc) - datetime.fromisoformat(started.replace("Z", "+00:00"))).total_seconds() / 60
                cols[1].progress(min(mins / 25, 0.99), text=f"{mins:.0f} of ~25 min")
            else:
                cols[1].write(r.get("conclusion", "").replace("_", " "))
            cols[2].link_button("Open on GitHub", r["html_url"])
            if status == "completed" and cols[3].button("View report", key=f"view{r['id']}"):
                st.session_state["view_run"] = r["id"]
                st.session_state["view_label"] = f"run #{r['run_number']}, {ago(started)}"
                st.rerun()

    runs_panel()

    rid = st.session_state.get("view_run")
    if rid is None:
        # show the newest finished report by default
        done = [r for r in gh("GET", f"/repos/{REPO}/actions/workflows/{WORKFLOW}/runs", params={"per_page": 10, "status": "completed"}).json().get("workflow_runs", [])]
        if done:
            rid = done[0]["id"]
            st.session_state["view_label"] = f"run #{done[0]['run_number']}, {ago(done[0].get('run_started_at'))}"
    if rid is not None:
        arts = gh("GET", f"/repos/{REPO}/actions/runs/{rid}/artifacts").json().get("artifacts", [])
        art = next((a for a in arts if a["name"] == "qa-report" and not a.get("expired")), None)
        st.divider()
        if not art:
            st.warning("This run has no report (it may have failed early or its report expired after 30 days).")
        else:
            data = artifact_zip(art["id"])
            show_report(files_from_zip(data), st.session_state.get("view_label", ""), data)


# ------------------------------------------------------------------ local mode
LOG = ROOT / "reports" / "streamlit-run.log"
PIDFILE = ROOT / "reports" / "streamlit-run.pid"


def running_pid() -> int | None:
    try:
        pid = int(PIDFILE.read_text())
        os.kill(pid, 0)
        return pid
    except Exception:
        return None


def local_mode() -> None:
    with st.sidebar:
        st.header("Start a test")
        choice = st.radio("What should be tested?", list(RUN_CHOICES), index=0)
        busy = running_pid()
        if st.button("▶ Start test", type="primary", use_container_width=True, disabled=bool(busy)):
            args = {"new-cycle": ["--fresh"], "continue": [], "retest-failed": ["--retest-failed"]}[RUN_CHOICES[choice]]
            LOG.parent.mkdir(parents=True, exist_ok=True)
            with open(LOG, "w") as log:
                p = subprocess.Popen(["npx", "tsx", "src/run.ts", *args], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
            PIDFILE.write_text(str(p.pid))
            st.rerun()
        if busy and st.button("■ Stop", use_container_width=True):
            os.kill(busy, 2)  # Ctrl+C: finishes current tests and writes the report

    @st.fragment(run_every=10)
    def live() -> None:
        if running_pid():
            st.info("A test is running…")
            if LOG.exists():
                st.code("\n".join(LOG.read_text(errors="replace").splitlines()[-25:]))
        elif LOG.exists():
            st.caption("Last run log (end)")
            st.code("\n".join(LOG.read_text(errors="replace").splitlines()[-8:]))

    live()
    rep = ROOT / "reports" / "latest"
    if (rep / "dashboard.html").exists() and not running_pid():
        files = {str(p.relative_to(rep)): p.read_bytes() for p in rep.rglob("*") if p.is_file()}
        show_report(files, datetime.fromtimestamp((rep / "results.json").stat().st_mtime).strftime("%d %b %Y, %H:%M"))


# ------------------------------------------------------------------ page
st.title("💎 VDB Website QA")
st.caption("Checks every link, popup, image and page on the store like a shopper would, and explains what is broken in plain words.")
if MODE == "local":
    local_mode()
else:
    github_mode()
